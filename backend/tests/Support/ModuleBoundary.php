    /** Every module, read from disk so a new one cannot be forgotten. */
    public static function modules(): array
    {
        $root = base_path('Modules');
        $modules = [];

        foreach (scandir($root) ?: [] as $entry) {
            if ($entry !== '.' && $entry !== '..' && is_dir("$root/$entry")) {
                $modules[] = $entry;
            }
        }

        sort($modules);

        return $modules;
    }

    /**
     * Every PHP file under a directory. Recursive, unlike the glob this
     * replaces.
     *
     * @return array<int, string>
     */
    public static function phpFilesUnder(string $directory): array
    {
        if (! is_dir($directory)) {
            return [];
        }

        $files = [];

        $iterator = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($directory, RecursiveDirectoryIterator::SKIP_DOTS)
        );

        /** @var SplFileInfo $file */
        foreach ($iterator as $file) {
            if ($file->isFile() && $file->getExtension() === 'php') {
                $files[] = str_replace('\\', '/', $file->getPathname());
            }
        }

        sort($files);

        return $files;
    }

    /** A module's own files, excluding its tests and its published contracts. */
    public static function sourceFilesOf(string $module): array
    {
        return array_values(array_filter(
            self::phpFilesUnder(base_path("Modules/$module")),
            fn (string $path): bool => ! str_contains($path, '/Tests/') && ! str_contains($path, '/Contracts/')
        ));
    }

    /** The path as the baseline names it: "Module/Relative/Path.php". */
    public static function relativePath(string $absolute): string
    {
        return str_replace(str_replace('\\', '/', base_path('Modules')).'/', '', str_replace('\\', '/', $absolute));
    }

    /**
     * Every cross-module import in one module that does not go through
     * Contracts/, after the platform exemptions below.
     *
     * @return array<string, array<int, string>> relative path => imported FQCNs
     */
    public static function violationsIn(string $module): array
    {
        $found = [];

        foreach (self::sourceFilesOf($module) as $path) {
            $relative = self::relativePath($path);

            preg_match_all(
                '/use (Modules\\\\(\w+)\\\\((?!Contracts\\\\)[\w\\\\]+));/',
                (string) file_get_contents($path),
                $matches,
                PREG_SET_ORDER
            );

            foreach ($matches as [, $fqcn, $target]) {
                if ($target === $module || self::isPlatformExempt($relative, $fqcn)) {
                    continue;
                }

                $found[$relative][] = $fqcn;
            }
        }

        foreach ($found as $relative => $imports) {
            $found[$relative] = array_values(array_unique($imports));
            sort($found[$relative]);
        }

        ksort($found);

        return $found;
    }

    /**
     * Two shared pieces of platform machinery that every module legitimately
     * uses, exempted by rule rather than listed file by file.
     *
     * They are not coupling between modules — they are the platform's own
     * scaffolding, and there is nowhere else for them to live. 49 of the 70
     * imports the corrected scan found are these two, which is why the raw
     * number is not the interesting one.
     */
    private static function isPlatformExempt(string $relative, string $fqcn): bool
    {
        // The shared schema helper. Every migration in the repository uses it
        // to declare UUID primary keys and soft deletes consistently; a
        // migration that hand-rolled them would be the actual defect.
        if (str_contains($relative, '/Database/Migrations/') && $fqcn === 'Modules\Core\Database\PlatformBlueprint') {
            return true;
        }

        // The shared aggregate concerns — HasDomainEvents and friends. A trait
        // every aggregate root in every module applies.
        return str_starts_with($fqcn, 'Modules\Core\Domain\Concerns\\');
    }

    /**
     * Violations that are NOT in the baseline — the ones a guard must fail on.
     *
     * @return array<int, string> human-readable "file -> class" lines
     */
    public static function unbaselinedViolationsIn(string $module): array
    {
        $new = [];

        foreach (self::violationsIn($module) as $relative => $imports) {
            $allowed = self::BASELINE[$relative] ?? [];

            foreach (array_diff($imports, $allowed) as $import) {
                $new[] = "$relative -> $import";
            }
        }

        return $new;
    }

    /**
     * Every model a controller imports, keyed by controller.
     *
     * @return array<string, array<int, string>>
     */
    public static function controllerModelImports(): array
    {
        $found = [];

        foreach (self::modules() as $module) {
            foreach (self::phpFilesUnder(base_path("Modules/$module/Presentation/HTTP/Controllers")) as $path) {
                preg_match_all(
                    '/use (Modules\\\\\w+\\\\[\w\\\\]*Models\\\\\w+);/',
                    (string) file_get_contents($path),
                    $matches
                );

                if ($matches[1] !== []) {
                    $imports = array_values(array_unique($matches[1]));
                    sort($imports);
                    $found[self::relativePath($path)] = $imports;
                }
            }
        }

        ksort($found);

        return $found;
    }

    /** @return array<int, string> */
    public static function unbaselinedControllerModelImports(): array
    {
        $new = [];

        foreach (self::controllerModelImports() as $relative => $imports) {
            foreach (array_diff($imports, self::CONTROLLER_MODEL_BASELINE[$relative] ?? []) as $import) {
                $new[] = "$relative -> $import";
            }
        }

        return $new;
    }

    /** @return array<int, string> */
    public static function staleControllerBaselineEntries(): array
    {
        $live = self::controllerModelImports();
        $stale = [];

        foreach (self::CONTROLLER_MODEL_BASELINE as $relative => $imports) {
            foreach ($imports as $import) {
                if (! in_array($import, $live[$relative] ?? [], true)) {
                    $stale[] = "$relative -> $import";
                }
            }
        }

        return $stale;
    }

    /**
     * Baseline entries that no longer describe a real violation.
     *
     * Without this the list rots: an import removed by later work would leave
     * a permanent entry, and the baseline would slowly stop meaning "this is
     * what we still owe". Paying debt down has to shrink the list, and this
     * is what makes that mandatory rather than polite.
     *
     * @return array<int, string>
     */
    public static function staleBaselineEntries(): array
    {
        $live = [];

        foreach (self::modules() as $module) {
            foreach (self::violationsIn($module) as $relative => $imports) {
                $live[$relative] = $imports;
            }
        }

        $stale = [];

        foreach (self::BASELINE as $relative => $imports) {
            foreach ($imports as $import) {
                if (! in_array($import, $live[$relative] ?? [], true)) {
                    $stale[] = "$relative -> $import";
                }
            }
        }

        return $stale;
    }
