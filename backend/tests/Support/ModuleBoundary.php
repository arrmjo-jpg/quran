/**
 * The one implementation behind every module-boundary guard — ADR-002.
 *
 * WHY THIS CLASS EXISTS. The guards it replaces used
 * `glob('Modules/X/**\/*.php')`, and PHP's glob has no recursive `**`: the
 * pattern degrades to a single `*`, so it matched only files sitting exactly
 * one directory below the module root. Measured before the rewrite:
 * **5 files out of ~40** in Contestants. The controller guard was worse —
 * `Controllers/**\/*.php` matched **nothing at all**, because controllers sit
 * directly in `Controllers/`, so no controller in the repository had ever been
 * checked.
 *
 * Those guards were green. A green test that inspects nothing is worse than a
 * missing one: it answers a question nobody re-asks.
 *
 * The module list is also discovered here rather than written down. The old
 * global guard carried a hardcoded array of fifteen names, and `Organization`
 * — added in Epic 2 — was never added to it, so an entire module sat outside
 * the check in both directions.
